type Lang = 'en' | 'ja';
const dicts: Record<Lang, Record<MessageKey, string>> = { en, ja };

let lang: Lang = (() => {
  try {
    const s = localStorage.getItem('fresnel.lang');
    if (s === 'en' || s === 'ja') return s;
  } catch {
    /* ignore */
  }
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('ja') ? 'ja' : 'en';
})();
const listeners = new Set<() => void>();
// the page language follows the UI language from the start (CJK glyph choice, screen readers)
if (typeof document !== 'undefined') document.documentElement.lang = lang;

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem('fresnel.lang', l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l;
  listeners.forEach((f) => f());
}

export function getLang(): Lang {
  return lang;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Re-renders the component when the language changes. */
export function useLang(): Lang {
  return useSyncExternalStore(
    (f) => {
      listeners.add(f);
      return () => listeners.delete(f);
    },
    () => lang,
  );
}
